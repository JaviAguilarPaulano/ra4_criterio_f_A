public class Computer {
    private int ram;
    private float cpu;
    private String motherBoard;

    // Setter para ram
    public void setRam(int ram) {
        this.ram = ram;
    }

    // Setter para cpu
    public void setCpu(float cpu) {
        this.cpu = cpu;
    }

    // Setter para motherBoard
    public void setMotherBoard(String motherBoard) {
        this.motherBoard = motherBoard;
    }
}
